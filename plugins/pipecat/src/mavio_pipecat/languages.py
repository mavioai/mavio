# Languages Whisper recognizes as another they are written in: Swiss German
# as German.
_WRITTEN_AS = {"gsw": "de"}


def whisper_code(tag: str) -> str | None:
    """Whisper's code of a BCP 47 tag; None for a language it does not
    recognize, or no tag."""
    base = tag.replace("_", "-").split("-")[0].lower()
    base = _WRITTEN_AS.get(base, base)
    if base == "jv":
        base = "jw"
    return base if base in LANGUAGES else None


def tag_of(language: str) -> str:
    """The BCP 47 tag of a language Whisper names by its code or its name,
    as OpenAI-compatible services answer; empty for an unknown one."""
    s = language.strip().lower()
    for code, name in LANGUAGES.items():
        if s in (code, name.lower()):
            return "jv" if code == "jw" else code
    return ""
