// caseFile is a test case file generated by tools/testport.
type caseFile struct {
	Theories []struct {
		Method string `json:"method"`
		Cases  []struct {
			ID   string                     `json:"id"`
			Skip string                     `json:"skip"`
			Args map[string]json.RawMessage `json:"args"`
		} `json:"cases"`
	} `json:"theories"`
	Facts []struct {
		Method string `json:"method"`
	} `json:"facts"`
}

func readCases(t *testing.T, name string) caseFile {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", "cases", name))
	if err != nil {
		t.Fatal(err)
	}
	var f caseFile
	if err := json.Unmarshal(data, &f); err != nil {
		t.Fatal(err)
	}
	return f
}

func arg(t *testing.T, args map[string]json.RawMessage, name string) string {
	t.Helper()
	var s string
	if err := json.Unmarshal(args[name], &s); err != nil {
		t.Fatalf("argument %s: %v", name, err)
	}
	return s
}

// portedCases runs the theories and facts of a ported case file. run maps a
// theory to a check of one case; skip gives the reason a theory, case ID or
// fact does not apply. Every theory and fact must be either run or skipped.
func portedCases(t *testing.T, name string, run map[string]func(t *testing.T, args map[string]json.RawMessage), skip map[string]string) {
	f := readCases(t, name)
	for _, th := range f.Theories {
		check, ok := run[th.Method]
		methodSkip, skipped := skip[th.Method]
		if !ok && !skipped {
			t.Errorf("%s: theory %s is neither run nor skipped", name, th.Method)
			continue
		}
		for _, c := range th.Cases {
			t.Run(c.ID, func(t *testing.T) {
				switch {
				case c.Skip != "":
					t.Skip("skipped in Jellyfin: " + c.Skip)
				case skip[c.ID] != "":
					t.Skip(skip[c.ID])
				case skipped:
					t.Skip(methodSkip)
				}
				check(t, c.Args)
			})
		}
	}
	for _, fact := range f.Facts {
		if _, ok := skip[fact.Method]; !ok {
			t.Errorf("%s: fact %s is neither ported nor skipped", name, fact.Method)
		}
	}
}

