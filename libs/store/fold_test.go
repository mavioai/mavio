func TestCleanValue(t *testing.T) {
	for in, want := range map[string]string{
		"Amélie":                 "amelie",
		"Ｃａｒｏｌ":                  "carol",
		"  The   Matrix ":        "the matrix",
		"Spider-Man: Homecoming": "spider man homecoming",
		"100% Wolf":              "100 wolf",
		"Ip_Man":                 "ip man",
		"千と千尋の神隠し":               "千と千尋の神隠し",
		"ガンダム":                   "ガンダム", // voicing marks are not diacritics
		"Pokémon: Ｔｈｅ Ｆｉｌｍ":      "pokemon the film",
		"Le cœur a ses raisons":  "le coeur a ses raisons",
		"!!!":                    "",
	} {
		if got := cleanValue(in); got != want {
			t.Errorf("cleanValue(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestSortKeyOrdering(t *testing.T) {
	keys := map[string]string{}
	for _, n := range []string{"Rocky 2", "Rocky 10", "The Shining", "Spider-Man", "Amélie"} {
		keys[n] = sortKey(n)
	}
	if keys["Rocky 2"] >= keys["Rocky 10"] {
		t.Errorf("Rocky 2 (%q) should sort before Rocky 10 (%q)", keys["Rocky 2"], keys["Rocky 10"])
	}
	if keys["The Shining"] >= keys["Spider-Man"] {
		t.Errorf("The Shining (%q) should sort under S, before Spider-Man (%q)", keys["The Shining"], keys["Spider-Man"])
	}
	if keys["Amélie"] != "amelie" {
		t.Errorf("sortKey(Amélie) = %q", keys["Amélie"])
	}
	// Non-ASCII titles are transliterated, so Chinese sorts by pinyin.
	if got := sortKey("千与千寻"); got != "qian yu qian xun" {
		t.Errorf("sortKey(千与千寻) = %q", got)
	}
	if sortKey("阿凡达") >= sortKey("霸王别姬") { // a fan da < ba wang bie ji
		t.Errorf("pinyin order: %q vs %q", sortKey("阿凡达"), sortKey("霸王别姬"))
	}
}

