// Command ftfygen generates data/ftfy.json, the character tables package
// subtitle's FixText (a port of ftfy's fix_text) works with:
//
//	go run ./internal/cmd/ftfygen -bazarr ~/src/bazarr -bazarr-commit <sha> \
//	    -cpython-lib /path/to/lib/python3.14 -cpython-version 3.14.5
//
// From a checkout of github.com/morpheus65535/bazarr (GPL-3.0) it reads
// ftfy 6.3.1 (Apache-2.0) as Bazarr vendors it in libs/ftfy:
//
//   - badness.py: MOJIBAKE_CATEGORIES, the character classes of ftfy's
//     mojibake heuristic;
//   - chardata.py: UTF8_CLUES, the character classes of the detector of
//     embedded UTF-8 mojibake.
//
// From the standard library of CPython (PSF-2.0), whose tables ftfy builds
// its own from at import time, it reads
//
//   - Lib/encodings/{cp1250,cp1251,cp1252,cp1253,cp1254,cp1257,iso8859_2,
//     mac_roman,cp437}.py: the decoding tables of the single-byte encodings
//     ftfy tries, with U+FFFE marking bytes they leave undefined;
//   - Lib/html/entities.py: the HTML5 named character references, from
//     which it builds ftfy's HTML_ENTITIES as chardata._build_html_entities
//     does.
//
// The output records its origin; it is never edited by hand.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"golang.org/x/text/cases"
	"golang.org/x/text/language"
)

func main() {
	bazarr := flag.String("bazarr", "", "Bazarr checkout")
	bazarrCommit := flag.String("bazarr-commit", "", "commit of the Bazarr checkout")
	cpythonLib := flag.String("cpython-lib", "", "CPython's Lib directory")
	cpythonVersion := flag.String("cpython-version", "", "version of that CPython")
	out := flag.String("out", "data", "output directory")
	flag.Parse()
	if *bazarr == "" || *bazarrCommit == "" || *cpythonLib == "" || *cpythonVersion == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := generate(*bazarr, *bazarrCommit, *cpythonLib, *cpythonVersion, *out); err != nil {
		slog.Error("ftfygen", "err", err)
		os.Exit(1)
	}
}

// source records where generated data comes from.
type source struct {
	Repository string `json:"repository"`
	Commit     string `json:"commit"`
	Path       string `json:"path"`
	License    string `json:"license"`
	Note       string `json:"note,omitempty"`
}

// output is data/ftfy.json.
type output struct {
	Comment            string            `json:"$comment"`
	Sources            []source          `json:"sources"`
	MojibakeCategories map[string]string `json:"mojibake_categories"`
	UTF8Clues          map[string]string `json:"utf8_clues"`
	Codecs             map[string]string `json:"codecs"`
	HTMLEntities       map[string]string `json:"html_entities"`
}

// codecFiles are the CPython modules of the encodings ftfy tries, by the
// name ftfy gives them (without its "sloppy-" prefix).
var codecFiles = map[string]string{
	"windows-1250": "cp1250.py",
	"windows-1251": "cp1251.py",
	"windows-1252": "cp1252.py",
	"windows-1253": "cp1253.py",
	"windows-1254": "cp1254.py",
	"windows-1257": "cp1257.py",
	"iso-8859-2":   "iso8859_2.py",
	"macroman":     "mac_roman.py",
	"cp437":        "cp437.py",
}

func generate(bazarr, bazarrCommit, cpythonLib, cpythonVersion, out string) error {
	names := runeNames()
	read := func(path string) (string, error) {
		data, err := os.ReadFile(path)
		return string(data), err
	}
	o := output{
		Comment: "Generated by internal/cmd/ftfygen. Do not edit.",
		Sources: []source{
			{
				Repository: "https://github.com/morpheus65535/bazarr", Commit: bazarrCommit,
				Path: "libs/ftfy/badness.py, libs/ftfy/chardata.py", License: "Apache-2.0",
				Note: "ftfy 6.3.1: MOJIBAKE_CATEGORIES and UTF8_CLUES",
			},
			{
				Repository: "https://github.com/python/cpython", Commit: "v" + cpythonVersion,
				Path: "Lib/encodings, Lib/html/entities.py", License: "PSF-2.0",
				Note: "decoding tables of the encodings ftfy tries, with U+FFFE for undefined bytes; " +
					"html_entities is ftfy's HTML_ENTITIES built from html.entities.html5",
			},
		},
		Codecs: map[string]string{},
	}

	src, err := read(filepath.Join(bazarr, "libs", "ftfy", "badness.py"))
	if err != nil {
		return err
	}
	if o.MojibakeCategories, err = parseStringDict(src, "MOJIBAKE_CATEGORIES", names); err != nil {
		return fmt.Errorf("badness.py: %w", err)
	}
	if src, err = read(filepath.Join(bazarr, "libs", "ftfy", "chardata.py")); err != nil {
		return err
	}
	if o.UTF8Clues, err = parseStringDict(src, "UTF8_CLUES", names); err != nil {
		return fmt.Errorf("chardata.py: %w", err)
	}

	latin1 := make([]rune, 256)
	for i := range latin1 {
		latin1[i] = rune(i)
	}
	o.Codecs["latin-1"] = string(latin1)
	for name, file := range codecFiles {
		if src, err = read(filepath.Join(cpythonLib, "encodings", file)); err != nil {
			return err
		}
		p, err := assignment(src, "decoding_table", names)
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		table, err := p.value()
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		s, ok := table.(string)
		if !ok || len([]rune(s)) != 256 {
			return fmt.Errorf("%s: decoding_table is not 256 characters", file)
		}
		o.Codecs[name] = s
	}

	if src, err = read(filepath.Join(cpythonLib, "html", "entities.py")); err != nil {
		return err
	}
	html5, err := parseStringDict(src, "html5", names)
	if err != nil {
		return fmt.Errorf("entities.py: %w", err)
	}
	o.HTMLEntities = htmlEntities(html5)

	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", " ")
	if err := enc.Encode(o); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, "ftfy.json"), b.Bytes(), 0o644)
}

// htmlEntities is ftfy's chardata._build_html_entities: the HTML5 entities
// that end in a semicolon, and the uppercased form of the lowercase ones
// whose uppercase name html.unescape leaves alone.
func htmlEntities(html5 map[string]string) map[string]string {
	upper := cases.Upper(language.Und)
	entities := map[string]string{}
	for name, char := range html5 {
		if !strings.HasSuffix(name, ";") {
			continue
		}
		entities["&"+name] = char
		if name == strings.ToLower(name) {
			nameUpper := strings.ToUpper(name)
			if !unescapes(html5, nameUpper) {
				entities["&"+nameUpper] = upper.String(char)
			}
		}
	}
	return entities
}

// unescapes reports whether Python's html.unescape changes "&"+name, for a
// name made of ASCII letters and digits and a final semicolon: whether its
// character reference, or a prefix of at least two characters of it, is a
// known entity.
func unescapes(html5 map[string]string, name string) bool {
	ref := strings.TrimSuffix(name, ";")
	if len(ref) > 32 {
		ref = ref[:32]
	} else {
		ref = name
	}
	if _, ok := html5[ref]; ok {
		return true
	}
	for x := len(ref) - 1; x > 1; x-- {
		if _, ok := html5[ref[:x]]; ok {
			return true
		}
	}
	return false
}

// runeNames maps Unicode character names to characters, for \N{...}.
func runeNames() map[string]rune {
	names := map[string]rune{}
	for r := rune(0); r <= 0x10FFFF; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		if name := runeName(r); name != "" && !strings.HasPrefix(name, "<") {
			names[name] = r
		}
	}
	return names
}

var assignmentRE = regexp.MustCompile(`(?m)^([A-Za-z_][A-Za-z0-9_]*)\b[^=\n]*=[ \t]*`)

// assignment returns a parser at the value assigned to name at the start of
// a line of a Python source, as in "name = ..." or "name: type = ...".
func assignment(src, name string, names map[string]rune) (*pyParser, error) {
	for _, m := range assignmentRE.FindAllStringSubmatchIndex(src, -1) {
		if src[m[2]:m[3]] == name && !strings.HasPrefix(src[m[1]:], "=") {
			return &pyParser{src: src, pos: m[1], names: names}, nil
		}
	}
	return nil, fmt.Errorf("no assignment to %s", name)
}

// parseStringDict parses the dict of strings assigned to name.
func parseStringDict(src, name string, names map[string]rune) (map[string]string, error) {
	p, err := assignment(src, name, names)
	if err != nil {
		return nil, err
	}
	v, err := p.value()
	if err != nil {
		return nil, err
	}
	d, ok := v.(map[string]string)
	if !ok {
		return nil, fmt.Errorf("%s is not a dict of strings", name)
	}
	return d, nil
}

