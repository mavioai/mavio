// Command subzerogen generates the data files package subtitle embeds for
// Bazarr's Subzero mods, language guessing and Chinese script detection:
//
//	go run ./internal/cmd/subzerogen -bazarr ~/src/bazarr -bazarr-commit <sha> \
//	    -zhon ~/src/zhon -zhon-commit <sha>
//
// From a checkout of github.com/morpheus65535/bazarr (GPL-3.0) it reads
//
//   - custom_libs/subzero/modification/dictionaries/data.py, Subzero's OCR
//     fix dictionaries: Subtitle Edit's OCR fix replace lists (GPL-3.0) with
//     Subzero's additions, in the order Subzero applies them, into ocr.json;
//   - libs/guess_language (guess_language-spirit, LGPL-3.0-or-later): its
//     Unicode block table and trigram models, into guesslang.json;
//   - libs/emoji/unicode_codes/emoji.json (emoji, BSD-3-Clause): the emoji
//     Subzero's emoji mod removes, into emoji.json;
//   - libs/tld/res/effective_tld_names.dat.txt (the Public Suffix List,
//     MPL-2.0, as package tld reads it): into tld.json.
//
// From a checkout of github.com/tsroten/zhon (MIT) it reads
// src/zhon/cedict/{simplified,traditional,all}.py, the CC-CEDICT
// (CC BY-SA 4.0) character sets hanzidentifier tells Chinese scripts apart
// with, into hanzi.json.
//
// Every output records its origin; it is never edited by hand.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"log/slog"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

func main() {
	bazarr := flag.String("bazarr", "", "Bazarr checkout")
	bazarrCommit := flag.String("bazarr-commit", "", "commit of the Bazarr checkout")
	zhon := flag.String("zhon", "", "zhon checkout")
	zhonCommit := flag.String("zhon-commit", "", "commit of the zhon checkout")
	out := flag.String("out", "data", "output directory")
	flag.Parse()
	if *bazarr == "" || *bazarrCommit == "" || *zhon == "" || *zhonCommit == "" {
		flag.Usage()
		os.Exit(2)
	}
	g := generator{bazarr: *bazarr, bazarrCommit: *bazarrCommit, zhon: *zhon, zhonCommit: *zhonCommit, out: *out}
	for _, step := range []func() error{g.ocr, g.guessLanguage, g.emoji, g.tld, g.hanzi} {
		if err := step(); err != nil {
			slog.Error("subzerogen", "err", err)
			os.Exit(1)
		}
	}
}

type generator struct {
	bazarr, bazarrCommit string
	zhon, zhonCommit     string
	out                  string
}

// source records where a generated file comes from.
type source struct {
	Repository string `json:"repository"`
	Commit     string `json:"commit"`
	Path       string `json:"path"`
	License    string `json:"license"`
	Note       string `json:"note,omitempty"`
}

const comment = "Generated by internal/cmd/subzerogen. Do not edit."

func (g generator) bazarrSource(path, license, note string) source {
	return source{Repository: "https://github.com/morpheus65535/bazarr", Commit: g.bazarrCommit, Path: path, License: license, Note: note}
}

// write writes v as JSON with one object member or array element per line,
// except for short arrays of scalars such as replacement pairs.
func (g generator) write(name string, v any) error {
	data, err := json.Marshal(v)
	if err != nil {
		return err
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	var tree any
	if err := dec.Decode(&tree); err != nil {
		return err
	}
	var b bytes.Buffer
	if err := format(&b, tree, ""); err != nil {
		return err
	}
	b.WriteByte('\n')
	return os.WriteFile(filepath.Join(g.out, name), b.Bytes(), 0o644)
}

func format(b *bytes.Buffer, v any, indent string) error {
	scalar := func(v any) error {
		enc := json.NewEncoder(b)
		enc.SetEscapeHTML(false)
		if err := enc.Encode(v); err != nil {
			return err
		}
		b.Truncate(b.Len() - 1)
		return nil
	}
	inner := indent + " "
	switch v := v.(type) {
	case map[string]any:
		b.WriteString("{\n")
		for i, k := range slices.Sorted(maps.Keys(v)) {
			b.WriteString(inner)
			if err := scalar(k); err != nil {
				return err
			}
			b.WriteString(": ")
			if err := format(b, v[k], inner); err != nil {
				return err
			}
			if i < len(v)-1 {
				b.WriteByte(',')
			}
			b.WriteByte('\n')
		}
		b.WriteString(indent + "}")
	case []any:
		short := len(v) <= 3 && !slices.ContainsFunc(v, func(e any) bool {
			switch e.(type) {
			case map[string]any, []any:
				return true
			}
			return false
		})
		if short {
			b.WriteByte('[')
			for i, e := range v {
				if i > 0 {
					b.WriteString(", ")
				}
				if err := scalar(e); err != nil {
					return err
				}
			}
			b.WriteByte(']')
			return nil
		}
		b.WriteString("[\n")
		for i, e := range v {
			b.WriteString(inner)
			if err := format(b, e, inner); err != nil {
				return err
			}
			if i < len(v)-1 {
				b.WriteByte(',')
			}
			b.WriteByte('\n')
		}
		b.WriteString(indent + "]")
	default:
		return scalar(v)
	}
	return nil
}

func (g generator) read(path string) (string, error) {
	data, err := os.ReadFile(path)
	return strings.TrimPrefix(string(data), "\ufeff"), err
}

func (g generator) ocr() error {
	const path = "custom_libs/subzero/modification/dictionaries/data.py"
	src, err := g.read(filepath.Join(g.bazarr, path))
	if err != nil {
		return err
	}
	data, err := parseAssignment(src, "data")
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	ocrGroups := []string{"WholeLines", "WholeWords", "BeginLines", "EndLines", "PartialLines", "PartialWordsAlways"}
	languages := map[string]map[string][][2]string{}
	for _, lang := range data.pairs {
		groups := map[string][][2]string{}
		for _, grp := range lang.value.pairs {
			if !slices.Contains(ocrGroups, grp.key.str) {
				return fmt.Errorf("%s: unknown group %q", path, grp.key.str)
			}
			for _, field := range grp.value.pairs {
				if field.key.str != "data" {
					continue // the patterns are rebuilt from the data
				}
				for _, kv := range field.value.pairs {
					groups[grp.key.str] = append(groups[grp.key.str], [2]string{kv.key.str, kv.value.str})
				}
			}
		}
		languages[lang.key.str] = groups
	}
	return g.write("ocr.json", struct {
		Comment   string                            `json:"$comment"`
		Source    source                            `json:"source"`
		Languages map[string]map[string][][2]string `json:"languages"`
	}{comment, g.bazarrSource(path, "GPL-3.0", "Subtitle Edit's OCR fix replace lists with Subzero's additions; keys of a language's ISO 639-2/T code"), languages})
}

// blockLine matches an assignment of guess_language's block table:
// BLOCKS[0x0:0x8] = ['Basic Latin'] * 0x8.
var blockLine = regexp.MustCompile(`(?m)^BLOCKS\[(0x[0-9a-f]+):(0x[0-9a-f]+)\] = \['([^']+)'\] \* 0x[0-9a-f]+`)

func (g generator) guessLanguage() error {
	const dir = "libs/guess_language"
	src, err := g.read(filepath.Join(g.bazarr, dir, "data", "__init__.py"))
	if err != nil {
		return err
	}
	var blocks [][3]any
	for _, m := range blockLine.FindAllStringSubmatch(src, -1) {
		lo, _ := strconv.ParseInt(m[1], 0, 32)
		hi, _ := strconv.ParseInt(m[2], 0, 32)
		blocks = append(blocks, [3]any{lo, hi, m[3]})
	}
	if len(blocks) == 0 {
		return errors.New("guess_language: no blocks")
	}
	files, err := filepath.Glob(filepath.Join(g.bazarr, dir, "data", "models", "*.py"))
	if err != nil {
		return err
	}
	models := map[string][]string{}
	for _, f := range files {
		name := strings.TrimSuffix(filepath.Base(f), ".py")
		if name == "__init__" {
			continue
		}
		src, err := g.read(f)
		if err != nil {
			return err
		}
		model, err := parseAssignment(src, "model")
		if err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		grams := make([]string, len(model.pairs))
		for _, kv := range model.pairs {
			i, err := strconv.Atoi(kv.value.str)
			if err != nil || i < 0 || i >= len(grams) || grams[i] != "" {
				return fmt.Errorf("%s: bad rank %q", f, kv.value.str)
			}
			grams[i] = kv.key.str
		}
		models[name] = grams
	}
	return g.write("guesslang.json", struct {
		Comment string              `json:"$comment"`
		Source  source              `json:"source"`
		Blocks  [][3]any            `json:"blocks"`
		Models  map[string][]string `json:"models"`
	}{comment, g.bazarrSource(dir, "LGPL-3.0-or-later", "guess_language-spirit 0.5.4: blocks are [first, end) of code point >> 4; models list trigrams by rank"), blocks, models})
}

func (g generator) emoji() error {
	const path = "libs/emoji/unicode_codes/emoji.json"
	data, err := os.ReadFile(filepath.Join(g.bazarr, path))
	if err != nil {
		return err
	}
	var m map[string]struct {
		Status int `json:"status"`
	}
	if err := json.Unmarshal(data, &m); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	var list, components []string
	for k, v := range m {
		list = append(list, k)
		if v.Status == 1 { // STATUS["component"]
			components = append(components, k)
		}
	}
	slices.Sort(list)
	slices.Sort(components)
	return g.write("emoji.json", struct {
		Comment    string   `json:"$comment"`
		Source     source   `json:"source"`
		Emoji      []string `json:"emoji"`
		Components []string `json:"components"`
	}{comment, g.bazarrSource(path, "BSD-3-Clause", "emoji 2.15.0: the keys of EMOJI_DATA, and those with the status component"), list, components})
}

func (g generator) tld() error {
	const path = "libs/tld/res/effective_tld_names.dat.txt"
	src, err := g.read(filepath.Join(g.bazarr, path))
	if err != nil {
		return err
	}
	var rules []string
	version := ""
	for _, line := range strings.SplitAfter(src, "\n") {
		if v, ok := strings.CutPrefix(line, "// VERSION: "); ok {
			version = strings.TrimSpace(v)
		}
		// As tld's MozillaTLDSourceParser: punycode names from comments,
		// other comments and empty lines skipped.
		if strings.Contains(line, "// xn--") {
			line = strings.Fields(line)[1]
		}
		if line == "" || line[0] == '/' || line[0] == '\n' {
			continue
		}
		rules = append(rules, strings.TrimSpace(line))
	}
	return g.write("tld.json", struct {
		Comment string   `json:"$comment"`
		Source  source   `json:"source"`
		Rules   []string `json:"rules"`
	}{comment, g.bazarrSource(path, "MPL-2.0", "the Public Suffix List "+version+" as tld 0.13.2 reads it"), rules})
}

func (g generator) hanzi() error {
	sets := map[string]string{}
	for _, name := range []string{"simplified", "traditional", "all"} {
		src, err := g.read(filepath.Join(g.zhon, "src", "zhon", "cedict", name+".py"))
		if err != nil {
			return err
		}
		v, err := parseAssignment(src, "CHARACTERS")
		if err != nil {
			return fmt.Errorf("zhon %s: %w", name, err)
		}
		runes := []rune(v.str)
		slices.Sort(runes)
		sets[name] = string(slices.Compact(runes))
	}
	return g.write("hanzi.json", struct {
		Comment     string `json:"$comment"`
		Source      source `json:"source"`
		Simplified  string `json:"simplified"`
		Traditional string `json:"traditional"`
		All         string `json:"all"`
	}{comment, source{
		Repository: "https://github.com/tsroten/zhon", Commit: g.zhonCommit, Path: "src/zhon/cedict",
		License: "MIT; the character lists come from CC-CEDICT (CC BY-SA 4.0)",
		Note:    "the character sets of hanzidentifier 1.3.0",
	}, sets["simplified"], sets["traditional"], sets["all"]})
}
