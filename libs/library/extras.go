// extraTypeNames are the names extras named after their owner get, numbered
// from the second extra of a type on.
var extraTypeNames = map[core.ExtraKind]string{
	core.ExtraClip:           "Clip",
	core.ExtraTrailer:        "Trailer",
	core.ExtraBehindTheScene: "Behind The Scenes",
	core.ExtraDeletedScene:   "Deleted Scene",
	core.ExtraInterview:      "Interview",
	core.ExtraScene:          "Scene",
	core.ExtraSample:         "Sample",
	core.ExtraThemeSong:      "Theme Song",
	core.ExtraThemeVideo:     "Theme Video",
	core.ExtraFeaturette:     "Featurette",
	core.ExtraShort:          "Short",
	core.ExtraOther:          "Extra",
}

func numberedExtraName(kind core.ExtraKind, seen int) string {
	name, ok := extraTypeNames[kind]
	if !ok {
		name = extraTypeNames[core.ExtraOther]
	}
	if seen == 0 {
		return name
	}
	return name + " " + strconv.Itoa(seen+1)
}

type extraCandidate struct {
	node  Node
	rule  *naming.ExtraRule
	mixed bool
}

// Extras finds the extras of owner among the entries of its folder and of
// the extras folders there ("trailers", "behind the scenes", …), listed
// through l. ownerIsFolder marks owners made of a folder, such as series
// and disc rips. An extra belongs to the owner when its name starts with
// the owner's, or when it lies in the owner's folder.
//
// Extras named after the owner, such as "Up (2009)-trailer.mkv", are named
// by their type and numbered in path order ("Trailer", "Trailer 2");
// others keep the title in their file name.
func (r *Resolver) Extras(owner Node, ownerIsFolder bool, entries []Entry, l Lister) ([]Node, error) {
	ownerInfo, ok := r.Parser.ResolveVideo(owner.Path, ownerIsFolder, true, containingFolder(owner.Path, ownerIsFolder))
	if !ok {
		return nil, nil
	}
	var candidates []extraCandidate
	add := func(p string, kind core.ExtraKind, rule *naming.ExtraRule, mixed bool) {
		if n, ok := r.resolveExtra(p, kind); ok {
			candidates = append(candidates, extraCandidate{n, rule, mixed})
		}
	}
	for _, e := range entries {
		if e.IsDir {
			if _, extras := r.extrasFolderKind(e.Name()); !extras || l == nil {
				continue
			}
			sub, err := l.List(e.Path)
			if err != nil {
				return nil, err
			}
			var files []Entry
			for _, f := range sub {
				if !f.IsDir && !IgnoredPath(f.Path) {
					files = append(files, f)
				}
			}
			for _, f := range files {
				if kind, rule, ok := r.extraKindFor(f.Path, ownerInfo, ownerIsFolder); ok {
					add(f.Path, kind, rule, len(files) > 1)
				}
			}
			continue
		}
		if kind, rule, ok := r.extraKindFor(e.Path, ownerInfo, ownerIsFolder); ok {
			add(e.Path, kind, rule, false)
		}
	}

	// Numbering follows the paths, not the order folders were listed in.
	slices.SortStableFunc(candidates, func(a, b extraCandidate) int { return cmp.Compare(a.node.Path, b.node.Path) })
	perKind := map[core.ExtraKind]int{}
	for _, c := range candidates {
		perKind[c.node.Extra]++
	}
	seen := map[core.ExtraKind]int{}
	extras := make([]Node, 0, len(candidates))
	for _, c := range candidates {
		n := c.node
		fileName := n.Name
		namedAfterOwner := false
		switch c.rule.Type {
		case naming.ExtraFilename:
			namedAfterOwner = true
		case naming.ExtraSuffix:
			namedAfterOwner = strings.EqualFold(n.Name, ownerInfo.Name)
		}
		if namedAfterOwner {
			n.Name = numberedExtraName(n.Extra, seen[n.Extra])
			seen[n.Extra]++
		}
		// Numbers shift as extras come and go, so any of them, or the
		// plain file name, may be what an earlier scan gave this extra.
		n.generatedNames = []string{fileName}
		for i := range perKind[n.Extra] {
			n.generatedNames = append(n.generatedNames, numberedExtraName(n.Extra, i))
		}
		n.InMixedFolder = c.mixed
		extras = append(extras, n)
	}
	return extras, nil
}

// RenewExtraName returns the name a known extra keeps after a rescan: its
// stored name, unless that is locked by the user or came from a local
// metadata file, the new name when the stored one was generated by a scan.
func RenewExtraName(stored string, locked bool, resolved Node) string {
	switch {
	case stored == "":
		return resolved.Name
	case locked:
		return stored
	case slices.Contains(resolved.generatedNames, stored):
		return resolved.Name
	}
	return stored
}

// extraKindFor ports ExtraResolver.TryGetExtraTypeForOwner.
func (r *Resolver) extraKindFor(p string, owner naming.VideoFile, ownerIsFolder bool) (core.ExtraKind, *naming.ExtraRule, bool) {
	kind, rule := r.Parser.ExtraInfo(p, "")
	if kind == "" || rule == nil {
		return "", nil, false
	}
	name, year := r.Parser.CleanDateTime(fileNameWithoutExt(p))
	parentDir := path.Dir(owner.Path)
	if ownerIsFolder {
		parentDir = owner.Path
	}
	delims := string(r.Parser.Options().VideoFlagDelimiters)
	trim := func(s string) string {
		return strings.TrimSpace(strings.TrimRight(strings.TrimSpace(s), delims))
	}
	ownerFile, ownerName, extraName := trim(owner.FileNameWithoutExtension()), trim(owner.Name), trim(name)
	valid := hasPrefixFold(extraName, ownerFile) || (hasPrefixFold(extraName, ownerName) && equalYears(year, owner.Year))
	if !valid {
		dir := path.Dir(p)
		if rule.Type == naming.ExtraDirectoryName {
			dir = path.Dir(dir)
		}
		valid = dir != "" && parentDir != "" && strings.EqualFold(dir, parentDir)
	}
	return kind, rule, valid
}

func hasPrefixFold(s, prefix string) bool {
	return prefix != "" && len(s) >= len(prefix) && strings.EqualFold(s[:len(prefix)], prefix)
}

func equalYears(a, b *int) bool { return (a == nil) == (b == nil) && (a == nil || *a == *b) }

// resolveExtra resolves an extra file: theme songs must be audio, other
// extras video.
func (r *Resolver) resolveExtra(p string, kind core.ExtraKind) (Node, bool) {
	if kind == core.ExtraThemeSong {
		if !r.Parser.IsAudioFile(p) {
			return Node{}, false
		}
		return Node{Kind: core.KindTrack, Path: p, Name: fileNameWithoutExt(p), Extra: kind}, true
	}
	v, ok := r.Parser.ResolveVideo(p, false, true, "")
	if !ok || v.IsStub {
		return Node{}, false
	}
	return Node{
		Kind: core.KindVideo, Path: p, Name: v.Name, Year: v.Year, Extra: kind,
		Format3D: format3D(v.Is3D, v.Format3D),
	}, true
}

func containingFolder(p string, isFolder bool) string {
	if isFolder {
		return p
	}
	return path.Dir(p)
}
